using Avalonia;
using Avalonia.Controls;
using Avalonia.Markup.Xaml;
using DynamicData;
using Wall.io.Interfaces;

namespace Wall.io.Views
{
    public partial class MainMenu : UserControl
    {

        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
        ////////////////////////////////////////////////////////Свойства и поля///////////////////////////////////////////////////////
        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
        //////////////////////////////////////////////////////////Конструкторы////////////////////////////////////////////////////////
        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

        public MainMenu()
        {
            InitializeComponent();
            InitializeMenuTabs();
        }


        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
        /////////////////////////////////////////////////////////////Методы///////////////////////////////////////////////////////////
        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

        private void InitializeMenuTabs()
        {
            MainMenuTabsList.Children.Add(CreateMenuTab(new LeaderboardTab()));
            MainMenuTabsList.Children.Add(CreateMenuTab(new GameSearchTab()));
            MainMenuTabsList.Children.Add(CreateMenuTab(new OptionsTab()));
        }

        private Control CreateMenuTab(IMainMenuTab ctrl)
        {
            var tb = new TextBlock { Text = ctrl.Name, Tag = ctrl };
            tb.DoubleTapped += MainMenuTab_DoubleTapped;
            return tb;
        }

        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
        //////////////////////////////////////////////////////Обработчики событий/////////////////////////////////////////////////////
        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

        private void MainMenuTab_DoubleTapped(object? sender, Avalonia.Input.TappedEventArgs e)
        {
            if (sender is TextBlock tb && tb.Tag is IMainMenuTab tab && tab is UserControl ctrl)
            {
                MainMenuTabContentField.Child = null;
                MainMenuTabContentField.Child = ctrl;
            }
        }

    }
}
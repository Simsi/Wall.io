using Avalonia;
using Avalonia.Controls;
using Avalonia.Markup.Xaml;
using Avalonia.Media;
using System;
using Wall.io.Controllers;

namespace Wall.io.Views
{
    public partial class Authorization : UserControl
    {

        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
        ////////////////////////////////////////////////////////Свойства и поля///////////////////////////////////////////////////////
        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
        //////////////////////////////////////////////////////////Конструкторы////////////////////////////////////////////////////////
        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

        public Authorization()
        {
            InitializeComponent();

            LogInButton.Click += LogInButton_Click;
        }

        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
        /////////////////////////////////////////////////////////////Методы///////////////////////////////////////////////////////////
        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
        private bool InvalidateLogIn(string username, string password)
        {
            return AppController.InvalidateUserLogin(username, password);
        }

        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
        //////////////////////////////////////////////////////Обработчики событий/////////////////////////////////////////////////////
        //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
        ///
        private void LogInButton_Click(object? sender, Avalonia.Interactivity.RoutedEventArgs e)
        {
            if (InvalidateLogIn(LoginTextBox.Text, PasswordTextBox.Text))
            {
                AppController.AppRootView.SwitchView(new MainMenu());
                LogInSuccessState.Text = "Успешная авторизация";
                LogInSuccessState.Foreground = Brushes.Green;
            }
            else
            {
                LogInSuccessState.IsVisible = true;
            }
        }
    }
}
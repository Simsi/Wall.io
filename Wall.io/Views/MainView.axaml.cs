using Avalonia;
using Avalonia.Controls;
using System;
using System.ComponentModel;
using Wall.io.Controllers;

namespace Wall.io.Views;

public partial class MainView : UserControl
{

    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    ////////////////////////////////////////////////////////Свойства и поля///////////////////////////////////////////////////////
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    
    /// <summary>
    /// Регистрация Control для размещения контекта внутри
    /// </summary>
    public static readonly StyledProperty<Control> ChildContentProperty = AvaloniaProperty.Register<UserControl, Control>(nameof(ChildContent));

    /// <summary>
    /// Control для контента, добавляемого из наследуемых классов
    /// </summary>
    public Control ChildContent
    {
        get => GetValue(ChildContentProperty);
        set => SetValue(ChildContentProperty, value);
    }

    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    //////////////////////////////////////////////////////////Конструкторы////////////////////////////////////////////////////////
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    
    public MainView()
    {
        InitializeComponent();

        AppController.AppRootView = this;

        SwitchView(new Authorization());
    }


    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    /////////////////////////////////////////////////////////////Методы///////////////////////////////////////////////////////////
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

    public void SwitchView(UserControl newView)
    {
        Control ctrl = ChildContent;
        ChildContent = null;

        ChildContent = newView;
    }

    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    //////////////////////////////////////////////////////Обработчики событий/////////////////////////////////////////////////////
    //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

}
